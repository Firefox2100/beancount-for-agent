"""Write the reference pages of the documentation that come straight from the code.

    uv run python scripts/generate_docs.py          # rewrite the pages of docs/docs/reference/
    uv run python scripts/generate_docs.py --check  # exit 1 when they are stale

The recipe page comes from the recipe registry; the tool and API pages from the generated contract. None can drift
from what the service does.
"""

import argparse
import json
import sys
from pathlib import Path

from beancount_mcp.recipes import default_registry

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = ROOT / "docs" / "docs" / "reference"
CONTRACT = ROOT / "integrations" / "contract" / "mcp-tools.json"
OPENAPI = ROOT / "integrations" / "contract" / "openapi.json"

GROUPS = {"read": "Read", "propose": "Propose", "recipe": "Recipes", "admin": "Admin"}
TYPE_ORDER = ["checking", "savings", "cash", "ewallet", "credit_card", "loan", "receivable", "payable", "brokerage"]


def _cell(text: str) -> str:
    return " ".join(str(text).replace("|", "\\|").split())


def _resolve(schema: dict, definitions: dict) -> dict:
    if "$ref" in schema:
        return definitions[schema["$ref"].rsplit("/", 1)[-1]]
    return schema


def _describe_type(schema: dict, definitions: dict) -> str:
    schema = _resolve(schema, definitions)
    options = schema.get("anyOf") or schema.get("oneOf")
    if options:
        kinds = []
        for option in options:
            option = _resolve(option, definitions)
            label = option.get("title") or option.get("type") or "value"
            if option.get("type") == "null" or label in kinds:
                continue
            if "properties" in option and option.get("title") == "Amount":
                label = "amount"
            kinds.append(label)
        return " or ".join(kinds)
    if schema.get("type") == "array":
        inner = _describe_type(schema.get("items", {}), definitions)
        return f"list of {inner}" if inner else "list"
    if "properties" in schema:
        return "amount" if schema.get("title") == "Amount" else "object"
    if schema.get("format") == "date":
        return "date"
    return schema.get("type", "value")


def recipes_page() -> str:
    registry = default_registry()
    kinds = registry.kinds()
    lines = [
        "---",
        "title: Account types and recipes",
        "sidebar_label: Recipes",
        "---",
        "",
        "{/* Generated by scripts/generate_docs.py from the recipe registry. Do not edit by hand. */}",
        "",
        "Each account type has a description and the recipes that apply to it. See [Recipes](../concepts/recipes.md) for how they behave.",
        "",
    ]
    for kind in [name for name in TYPE_ORDER if name in kinds] + sorted(set(kinds) - set(TYPE_ORDER)):
        applicable = sorted(registry.for_kind(kind), key=lambda recipe: recipe.id)
        lines += [f"## `{kind}`", "", kinds[kind], ""]
        for recipe in applicable:
            schema = recipe.params.model_json_schema()
            definitions = schema.get("$defs", {})
            required = set(schema.get("required", []))
            lines += [f"### `{recipe.id}`", "", f"{recipe.description}", ""]
            lines += ["| Parameter | Type | Required | Description |", "| --- | --- | --- | --- |"]
            for name, spec in schema.get("properties", {}).items():
                description = spec.get("description") or _resolve(spec, definitions).get("description", "")
                lines.append(
                    f"| `{name}` | {_cell(_describe_type(spec, definitions))} | {'yes' if name in required else ''} | {_cell(description)} |"
                )
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def tools_page() -> str:
    tools = json.loads(CONTRACT.read_text())
    lines = [
        "---",
        "title: MCP tools",
        "sidebar_label: MCP tools",
        "---",
        "",
        "{/* Generated by scripts/generate_docs.py from integrations/contract/mcp-tools.json. Do not edit by hand. */}",
        "",
        "Every tool that changes anything is a **proposal**: it returns a pending change that a person approves elsewhere. "
        "There is no approve or reject tool. The `ledger` argument can be left out when exactly one ledger exists.",
        "",
    ]
    for tag, title in GROUPS.items():
        group = [tool for tool in tools if tag in tool["tags"]]
        if tag == "propose":
            group = [tool for tool in tools if "propose" in tool["tags"] and "recipe" not in tool["tags"]]
        if tag == "admin":
            group = [tool for tool in tools if "admin" in tool["tags"] and "propose" not in tool["tags"]]
        if not group:
            continue
        lines += [f"## {title}", ""]
        for tool in sorted(group, key=lambda item: item["name"]):
            schema = tool["inputSchema"]
            required = set(schema.get("required", []))
            definitions = schema.get("$defs", {})
            lines += [f"### `{tool['name']}`", "", tool["description"], ""]
            properties = schema.get("properties", {})
            if properties:
                lines += ["| Argument | Type | Required |", "| --- | --- | --- |"]
                for name, spec in properties.items():
                    lines.append(f"| `{name}` | {_cell(_describe_type(spec, definitions))} | {'yes' if name in required else ''} |")
                lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _endpoints(agent: bool) -> str:
    spec = json.loads(OPENAPI.read_text())
    rows: dict[str, list[tuple[str, str, str]]] = {}
    for path, methods in spec["paths"].items():
        if path.startswith("/agent") != agent:
            continue
        for method, operation in methods.items():
            tag = (operation.get("tags") or ["other"])[0]
            text = operation.get("description") or operation.get("summary") or ""
            rows.setdefault(tag, []).append((method.upper(), path, text.split("\n")[0]))
    lines = []
    for tag in sorted(rows):
        lines += [f"## {tag.capitalize()}", "", "| Method | Path | What it does |", "| --- | --- | --- |"]
        for method, path, text in sorted(rows[tag], key=lambda row: (row[1], row[0])):
            lines.append(f"| `{method}` | `{path}` | {_cell(text)} |")
        lines.append("")
    return "\n".join(lines)


def agent_api_page() -> str:
    return "\n".join([
        "---",
        "title: Agent API",
        "---",
        "",
        "{/* Generated by scripts/generate_docs.py from integrations/contract/openapi.json. Do not edit by hand. */}",
        "",
        "The agent API serves the [MCP tools](mcp-tools.md)' operations over HTTP, for harness plugins that register native tools instead of using MCP. "
        "It is a thin adapter over the same service the MCP tools use, so account matching, recipe choice, lenient input and bank-detail masking are identical.",
        "",
        "- **Callers are always agents**, whatever `X-Actor` says. The client and session come from `X-Client-Id` and `X-Session-Id`.",
        "- **Everything that writes is a proposal.** Nothing here approves one: approval uses the [REST API](rest-api.md) as a user.",
        "- **`ledger` is an optional field** on every request, so a plugin can keep the active ledger in its own session and leave it out of the tool schemas the model sees. With exactly one ledger it can always be left out.",
        "- Send `Authorization: Bearer <token>` when the service has a token.",
        "",
        _endpoints(True),
    ]).rstrip() + "\n"


def rest_api_page() -> str:
    return "\n".join([
        "---",
        "title: REST API",
        "---",
        "",
        "{/* Generated by scripts/generate_docs.py from integrations/contract/openapi.json. Do not edit by hand. */}",
        "",
        "The complete CRUD surface, used by people, scripts and harness plugins that act as the user. The service also serves its OpenAPI document at `/openapi.json` and interactive docs at `/docs`.",
        "",
        "- **Writes commit at once** for a `user`, with an optional `If-Match` header carrying the last seen ledger version (`412` when stale). Agents are refused (`403`) when approval is required: they use [proposals](../concepts/proposals.md).",
        "- **Proposals** live under `/ledgers/{ledger_id}/changes`. Approve and reject take a JSON body, which may be `{}`.",
        "- **Errors** are `{\"detail\": ...}`: `404` not found, `409` conflict, `412` stale version, `422` invalid, `428` version required, `403` not allowed.",
        "- The browser interface under `/ui/` is not part of this API.",
        "",
        _endpoints(False),
    ]).rstrip() + "\n"


def build() -> dict[Path, str]:
    return {
        REFERENCE / "recipes.md": recipes_page(),
        REFERENCE / "mcp-tools.md": tools_page(),
        REFERENCE / "agent-api.md": agent_api_page(),
        REFERENCE / "rest-api.md": rest_api_page(),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail instead of writing when the pages are stale")
    args = parser.parse_args(argv)
    pages = build()
    stale = [path for path, content in pages.items() if not path.exists() or path.read_text() != content]
    if args.check:
        if stale:
            print(f"stale documentation: {', '.join(path.name for path in stale)}. Run scripts/generate_docs.py", file=sys.stderr)
            return 1
        return 0
    REFERENCE.mkdir(parents=True, exist_ok=True)
    for path in stale:
        path.write_text(pages[path])
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
